export const crewInstructionLimit = 8000;

// تحقق صافٍ قابل للاختبار: يُرفض أي تعريف يخالف حوكمة المشروع.
export function validateCrew(crew = agentCrew) {
  const problems = [];
  const roles = Object.keys(crew);
  if (!roles.length) problems.push("الطاقم فارغ — لا أدوار.");
  for (const role of roles) {
    const entry = crew[role] ?? {};
    const instructions = String(entry.instructions ?? "");
    const model = String(entry.model ?? "");
    if (!instructions.trim()) problems.push(`${role}: تعليمات فارغة`);
    if (instructions.length > crewInstructionLimit) {
      problems.push(`${role}: التعليمات ${instructions.length} حرفًا تتجاوز الحد ${crewInstructionLimit} (يُقصّ بصمت)`);
    }
    if (!model.trim()) problems.push(`${role}: نموذج فارغ`);
    if (/\s/.test(model)) problems.push(`${role}: اسم النموذج يحتوي مسافة`);
    if (/^(gpt|claude|gemini|openai|anthropic)/i.test(model)) {
      problems.push(`${role}: نموذج خارجي «${model}» — ممنوع؛ الطاقم محلي فقط (لا تُصدَّر بيانات)`);
    }
    if (!/^[\w.\-/:]+$/.test(model)) problems.push(`${role}: اسم النموذج يحتوي محارف غير متوقعة`);
  }
  return problems;
}
