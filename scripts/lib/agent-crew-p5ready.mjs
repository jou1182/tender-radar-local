// تحقق صافٍ قابل للاختبار: يُرفض أي تعريف يخالف حوكمة المشروع — برسالة واحدة لكل خلل.
export function validateCrew(crew = agentCrew) {
  const problems = [];
  const roles = Object.keys(crew || {});
  if (!roles.length) problems.push("الطاقم فارغ");
  for (const role of roles) {
    const model = String(crew[role]?.model ?? "");
    const instructions = String(crew[role]?.instructions ?? "");
    if (!model.trim()) problems.push(`${role}: نموذج فارغ`);
    else if (/\s/.test(model)) problems.push(`${role}: اسم النموذج يحتوي مسافة`);
    else if (!/^[\w.\-/:]+$/.test(model)) problems.push(`${role}: اسم النموذج يحتوي محارف غير متوقعة`);
    if (/^(gpt|claude|gemini|openai|anthropic)/i.test(model.trim())) {
      problems.push(`${role}: نموذج خارجي «${model}» — ممنوع؛ الطاقم محلي فقط (لا تُصدَّر بيانات)`);
    }
    if (!instructions.trim()) problems.push(`${role}: التعليمات فارغة`);
    if (instructions.length > crewInstructionLimit) {
      problems.push(`${role}: التعليمات ${instructions.length} حرفًا تتجاوز الحد ${crewInstructionLimit} (يُقصّ بصمت)`);
    }
  }
  return problems;
}

// P5-AGENTS-READY (ملاحظة المراجعة S1 الملزمة): بوابة هوية الهدف. وجود .radar-data
// أو حتى ملف قاعدة لا يكفي — في الشجرة 11 قاعدة شقيقة تحمل الملف نفسه، فأي خطأ مسار
// كان يمرّ بصمت. المُميِّز الفعلي لقاعدة التشغيل هو وجود بيانات تشغيل (منافسات أو
// مزامنات)؛ فقاعدة خالية تُرفض إلا بعلم صريح --allow-empty-db. دالة نقية مختبَرة.
export function classifyTarget({ dbExists, allowEmptyDb = false, tenders = 0, syncRuns = 0 } = {}) {
  if (!dbExists) {
    if (allowEmptyDb) return { ok: true, newTarget: true, reason: "هدف جديد بعلم صريح" };
    return {
      ok: false,
      error: "NO_DB",
      message: "لا توجد قاعدة في الهدف — الهوية غير مؤكَّدة. إن كان هدفًا جديدًا فعلًا فمرّر --allow-empty-db صراحةً.",
    };
  }
  if (!allowEmptyDb && tenders === 0 && syncRuns === 0) {
    return {
      ok: false,
      error: "EMPTY_STORE",
      message: "الهدف لا يحتوي بيانات تشغيل (0 منافسة و0 مزامنة) — يشبه قاعدة اختبار أو فرعًا شقيقًا لا قاعدة التشغيل. أُوقف بلا كتابة؛ إن كنت تقصدها فعلًا فمرّر --allow-empty-db صراحةً.",
    };
  }
  return { ok: true, newTarget: false, reason: `بيانات تشغيل: ${tenders} منافسة و${syncRuns} مزامنة` };
}
